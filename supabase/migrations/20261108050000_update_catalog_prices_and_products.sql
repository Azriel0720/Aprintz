insert into public.products (
  name, slug, category, category_id, description, base_price, unit, stock_quantity, is_active
)
select
  seed.name,
  seed.slug,
  category.name,
  category.id,
  'Cetak ' || seed.name || ' untuk kebutuhan ' || category.name || '. Spesifikasi akhir dikonfirmasi sebelum produksi.',
  seed.base_price,
  seed.unit,
  0,
  true
from aprintz_catalog_seed as seed
join public.categories as category on category.slug = seed.category_slug
on conflict (slug) do update set
  name = excluded.name,
  category = excluded.category,
  category_id = excluded.category_id,
  description = excluded.description,
  base_price = excluded.base_price,
  unit = excluded.unit,
  is_active = true;

update public.products as product
set is_active = false,
    description = 'Produk ini tidak termasuk dalam katalog aktif terbaru APRINTZ.'
where product.description = 'Harga referensi sementara dari daftar yang diberikan. Konfirmasi harga dan spesifikasi final kepada admin APRINTZ sebelum pemesanan.'
  and not exists (
    select 1 from aprintz_catalog_seed as seed where seed.slug = product.slug
  );

notify pgrst, 'reload schema';

commit;
